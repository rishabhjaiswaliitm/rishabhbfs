function getActivePage() {
  return quizPages[state.pageIndex];
}

function applyTheme(theme) {
  const isLight = theme === "light";
  document.body.classList.toggle("light-mode", isLight);
  themeToggle.setAttribute("aria-pressed", String(isLight));
  themeToggleText.textContent = isLight ? "Dark Mode" : "Light Mode";
}

function loadTheme() {
  applyTheme("dark");
}

function toggleTheme() {
  const nextTheme = document.body.classList.contains("light-mode")
    ? "dark"
    : "light";
  applyTheme(nextTheme);
}

function shuffleAnswers(question) {
  return question.answers
    .map((answer, index) => ({ answer, isCorrect: index === question.correct }))
    .sort(() => Math.random() - 0.5);
}

function renderPageSelector() {
  pageButtonsEl.innerHTML = "";

  quizPages.forEach((page, pageIndex) => {
    const button = document.createElement("button");
    button.className = "page-button";
    button.type = "button";
    button.textContent = page.title;
    button.setAttribute("aria-pressed", String(pageIndex === state.pageIndex));
    button.addEventListener("click", () => loadPage(pageIndex));
    pageButtonsEl.appendChild(button);
  });
}

function resetQuizState() {
  state.index = 0;
  state.score = 0;
  state.streak = 0;
  state.selected = null;
  state.checked = false;
  state.finished = false;
}

function loadPage(pageIndex) {
  state.pageIndex = pageIndex;
  questions = getActivePage().questions;
  resetQuizState();
  renderPageSelector();
  renderQuestion();
}

function renderQuestion() {
  const question = questions[state.index];
  const activePage = getActivePage();
  state.selected = null;
  state.checked = false;

  pageTitleEl.textContent = activePage.title;
  scoreEl.textContent = state.score;
  streakEl.textContent = state.streak;
  currentQuestionEl.textContent = state.index + 1;
  totalQuestionsEl.textContent = questions.length;
  progressFillEl.style.width = `${(state.index / questions.length) * 100}%`;
  topicEl.textContent = `${activePage.title} - ${question.topic}`;
  questionTextEl.textContent = question.question;
  feedbackEl.hidden = true;
  nextButton.textContent =
    state.index === questions.length - 1 ? "Show Results" : "Next Question";
  nextButton.disabled = true;
  answersEl.innerHTML = "";

  shuffleAnswers(question).forEach((option, index) => {
    const button = document.createElement("button");
    button.className = "answer-button";
    button.type = "button";
    button.dataset.correct = String(option.isCorrect);
    button.dataset.shortcut = String(index + 1);
    button.innerHTML = `
      <span class="answer-key">${index + 1}</span>
      <span class="answer-text"></span>
    `;
    button.querySelector(".answer-text").textContent = option.answer;
    button.addEventListener("click", () => selectAnswer(button));
    answersEl.appendChild(button);
  });
}

function selectAnswer(button) {
  if (state.checked) {
    return;
  }

  document
    .querySelectorAll(".answer-button")
    .forEach((answerButton) => answerButton.classList.remove("selected"));
  button.classList.add("selected");
  state.selected = button;

  const isCorrect = button.dataset.correct === "true";

  if (isCorrect) {
    state.checked = true;
    state.score += 10;
    state.streak += 1;
    button.classList.add("correct");
    document.querySelectorAll(".answer-button").forEach((answerButton) => {
      answerButton.disabled = true;
    });
    feedbackTitleEl.textContent = "Correct";
    feedbackTextEl.textContent = questions[state.index].explanation;
    nextButton.disabled = false;
  } else {
    state.streak = 0;
    button.classList.add("incorrect");
    feedbackTitleEl.textContent = "Not quite";
    feedbackTextEl.textContent = "Try again. You can keep choosing until you find the correct answer.";
  }

  scoreEl.textContent = state.score;
  streakEl.textContent = state.streak;
  feedbackEl.hidden = false;
}

function moveNext() {
  if (state.finished) {
    restartGame();
    return;
  }

  if (state.index < questions.length - 1) {
    state.index += 1;
    renderQuestion();
  } else {
    renderResults();
  }
}

function renderResults() {
  const percent = Math.round((state.score / (questions.length * 10)) * 100);
  progressFillEl.style.width = "100%";
  topicEl.textContent = `${getActivePage().title} - Finished`;
  questionTextEl.textContent = `You scored ${state.score} out of ${questions.length * 10} (${percent}%).`;
  answersEl.innerHTML = `<p class="result-message">${getResultMessage(percent)}</p>`;
  feedbackEl.hidden = true;
  nextButton.textContent = "Play Again";
  nextButton.disabled = false;
  state.checked = true;
  state.finished = true;
}

function getResultMessage(percent) {
  if (percent >= 85) {
    return "Strong command of the lecture: you caught the main ideas about sources, comparison, bias, and urban history.";
  }

  if (percent >= 60) {
    return "Good start. Review the questions you missed, especially the limits of evidence and why civilization is framed as urban history.";
  }

  return "Replay once more and focus on the lecture's core claims: ancient history needs comparison, careful source use, and awareness of bias.";
}

function restartGame() {
  resetQuizState();
  renderQuestion();
}

