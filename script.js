function getPageLecture(page) {
  return page.lectureNumber || (page.pageNumber >= 9 ? 2 : 1);
}

function getLectureNumbers() {
  return [...new Set(quizPages.map(getPageLecture))].sort((a, b) => a - b);
}

function getLecturePageEntries(lectureNumber = state.lectureNumber) {
  return quizPages
    .map((page, pageIndex) => ({ page, pageIndex }))
    .filter(({ page }) => getPageLecture(page) === lectureNumber);
}

function getActivePage() {
  return quizPages[state.pageIndex];
}

function saveSelectedPage() {
  localStorage.setItem(savedPageKey, String(getActivePage().pageNumber));
}

function loadSavedPage() {
  const savedPageNumber = Number(localStorage.getItem(savedPageKey));
  const normalizedPageNumber = savedPageNumber === 1 ? 3 : savedPageNumber;
  const savedPageIndex = quizPages.findIndex(
    (page) => page.pageNumber === normalizedPageNumber
  );

  if (savedPageIndex >= 0) {
    state.pageIndex = savedPageIndex;
    state.lectureNumber = getPageLecture(quizPages[savedPageIndex]);
    questions = quizPages[savedPageIndex].questions;
  }
}

function applyTheme(theme) {
  const isLight = theme === "light";
  document.body.classList.toggle("light-mode", isLight);
  themeToggle.setAttribute("aria-pressed", String(isLight));
  themeToggleText.textContent = isLight ? "Dark Mode" : "Light Mode";
}

function loadTheme() {
  applyTheme("dark");
}

function toggleTheme() {
  const nextTheme = document.body.classList.contains("light-mode")
    ? "dark"
    : "light";
  applyTheme(nextTheme);
}

function shuffleAnswers(question) {
  return question.answers
    .map((answer, index) => ({ answer, isCorrect: index === question.correct }))
    .sort(() => Math.random() - 0.5);
}

function renderPageSelector() {
  pageButtonsEl.innerHTML = "";

  getLecturePageEntries().forEach(({ page, pageIndex }) => {
    const button = document.createElement("button");
    button.className = "page-button";
    button.type = "button";
    button.textContent = page.title;
    button.setAttribute("aria-pressed", String(pageIndex === state.pageIndex));
    button.addEventListener("click", () => loadPage(pageIndex));
    pageButtonsEl.appendChild(button);
  });
}

function renderLectureSelector() {
  lectureSelectEl.innerHTML = "";

  getLectureNumbers().forEach((lectureNumber) => {
    const option = document.createElement("option");
    option.value = String(lectureNumber);
    option.textContent = `Lecture ${lectureNumber}`;
    lectureSelectEl.appendChild(option);
  });

  lectureSelectEl.value = String(state.lectureNumber);
}

function resetQuizState() {
  state.index = 0;
  state.score = 0;
  state.streak = 0;
  state.selected = null;
  state.checked = false;
  state.finished = false;
}

function loadPage(pageIndex) {
  state.pageIndex = pageIndex;
  state.lectureNumber = getPageLecture(getActivePage());
  questions = getActivePage().questions;
  saveSelectedPage();
  resetQuizState();
  renderLectureSelector();
  renderPageSelector();
  renderQuestion();
}

function loadLecture(lectureNumber) {
  const firstPageEntry = getLecturePageEntries(lectureNumber)[0];

  if (!firstPageEntry) {
    return;
  }

  state.lectureNumber = lectureNumber;
  loadPage(firstPageEntry.pageIndex);
}

function renderQuestion() {
  const question = questions[state.index];
  const activePage = getActivePage();
  state.selected = null;
  state.checked = false;

  pageTitleEl.textContent = activePage.title;
  scoreEl.textContent = state.score;
  streakEl.textContent = state.streak;
  currentQuestionEl.textContent = state.index + 1;
  totalQuestionsEl.textContent = questions.length;
  progressFillEl.style.width = `${(state.index / questions.length) * 100}%`;
  topicEl.textContent = `${activePage.title} - ${question.topic}`;
  questionTextEl.textContent = question.question;
  feedbackEl.hidden = true;
  nextButton.textContent =
    state.index === questions.length - 1 ? "Show Results" : "Next Question";
  nextButton.disabled = true;
  answersEl.innerHTML = "";

  shuffleAnswers(question).forEach((option, index) => {
    const button = document.createElement("button");
    button.className = "answer-button";
    button.type = "button";
    button.dataset.correct = String(option.isCorrect);
    button.dataset.shortcut = String(index + 1);
    button.innerHTML = `
      <span class="answer-key">${index + 1}</span>
      <span class="answer-text"></span>
    `;
    button.querySelector(".answer-text").textContent = option.answer;
    button.addEventListener("click", () => selectAnswer(button));
    answersEl.appendChild(button);
  });
}

function selectAnswer(button) {
  if (state.checked) {
    return;
  }

  document
    .querySelectorAll(".answer-button")
    .forEach((answerButton) => answerButton.classList.remove("selected"));
  button.classList.add("selected");
  state.selected = button;

  const isCorrect = button.dataset.correct === "true";

  if (isCorrect) {
    state.checked = true;
    state.score += 10;
    state.streak += 1;
    button.classList.add("correct");
    document.querySelectorAll(".answer-button").forEach((answerButton) => {
      answerButton.disabled = true;
    });
    feedbackTitleEl.textContent = "Correct";
    feedbackTextEl.textContent = questions[state.index].explanation;
    nextButton.disabled = false;
  } else {
    state.streak = 0;
    button.classList.add("incorrect");
    feedbackTitleEl.textContent = "Not quite";
    feedbackTextEl.textContent = "Try again. You can keep choosing until you find the correct answer.";
  }

  scoreEl.textContent = state.score;
  streakEl.textContent = state.streak;
  feedbackEl.hidden = false;
}

function moveNext() {
  if (state.finished) {
    restartGame();
    return;
  }

  if (state.index < questions.length - 1) {
    state.index += 1;
    renderQuestion();
  } else {
    renderResults();
  }
}

function renderResults() {
  const percent = Math.round((state.score / (questions.length * 10)) * 100);
  progressFillEl.style.width = "100%";
  topicEl.textContent = `${getActivePage().title} - Finished`;
  questionTextEl.textContent = `You scored ${state.score} out of ${questions.length * 10} (${percent}%).`;
  answersEl.innerHTML = `<p class="result-message">${getResultMessage(percent)}</p>`;
  feedbackEl.hidden = true;
  nextButton.textContent = "Play Again";
  nextButton.disabled = false;
  state.checked = true;
  state.finished = true;
}

function getResultMessage(percent) {
  if (percent >= 85) {
    return "Strong command of the lecture: you caught the main ideas about sources, comparison, bias, and urban history.";
  }

  if (percent >= 60) {
    return "Good start. Review the questions you missed, especially the limits of evidence and why civilization is framed as urban history.";
  }

  return "Replay once more and focus on the lecture's core claims: ancient history needs comparison, careful source use, and awareness of bias.";
}

function restartGame() {
  resetQuizState();
  renderQuestion();
}

function createQuizPdf(mode) {
  const pageWidth = 612;
  const pageHeight = 792;
  const margin = 48;
  const themes = {
    dark: {
      background: [11, 17, 20],
      panel: [17, 27, 31],
      text: [237, 244, 239],
      muted: [168, 184, 184],
      accent: [240, 134, 86],
      correct: [115, 221, 209]
    },
    light: {
      background: [255, 250, 240],
      panel: [248, 251, 248],
      text: [23, 35, 38],
      muted: [65, 85, 89],
      accent: [143, 79, 53],
      correct: [29, 78, 83]
    }
  };
  const theme = themes[mode];
  const pages = [];
  let commands = [];
  let y = pageHeight - margin;

  function color(values) {
    return values.map((value) => (value / 255).toFixed(3)).join(" ");
  }

  function cleanText(value) {
    return String(value)
      .replace(/[“”]/g, '"')
      .replace(/[‘’]/g, "'")
      .replace(/—/g, " - ")
      .replace(/–/g, "-")
      .replace(/[^\x20-\x7e]/g, "");
  }

  function escapePdfText(value) {
    return cleanText(value).replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
  }

  function wrapText(value, maxCharacters) {
    const words = cleanText(value).split(/\s+/);
    const lines = [];
    let line = "";

    words.forEach((word) => {
      const candidate = line ? `${line} ${word}` : word;
      if (candidate.length > maxCharacters && line) {
        lines.push(line);
        line = word;
      } else {
        line = candidate;
      }
    });

    if (line) {
      lines.push(line);
    }

    return lines;
  }

  function addRectangle(x, bottom, width, height, fill) {
    commands.push(`${color(fill)} rg ${x} ${bottom} ${width} ${height} re f`);
  }

  function addText(value, x, baseline, size, fill, font = "F1") {
    commands.push(
      `BT /${font} ${size} Tf ${color(fill)} rg ${x} ${baseline} Td (${escapePdfText(value)}) Tj ET`
    );
  }

  function addWrappedText(value, x, size, fill, maxCharacters, lineHeight, font = "F1") {
    wrapText(value, maxCharacters).forEach((line) => {
      addText(line, x, y, size, fill, font);
      y -= lineHeight;
    });
  }

  function startPage() {
    commands = [];
    pages.push(commands);
    y = pageHeight - margin;
    addRectangle(0, 0, pageWidth, pageHeight, theme.background);
  }

  function ensureSpace(requiredHeight) {
    if (y - requiredHeight < margin) {
      startPage();
    }
  }

  function addHeader() {
    addText("Lecture 1 MCQ Game", margin, y, 11, theme.accent, "F2");
    y -= 26;
    addWrappedText("History of Ancient World Glocal: Cities, Civilizations, and Sources", margin, 25, theme.text, 36, 30, "F2");
    addText(`${getActivePage().title}  |  Mode: ${mode === "light" ? "Light" : "Dark"}  |  Score at export: ${state.score} / ${questions.length * 10}`, margin, y, 10, theme.muted);
    y -= 28;
    commands.push(`${color(theme.accent)} RG 1.4 w ${margin} ${y} m ${pageWidth - margin} ${y} l S`);
    y -= 28;
  }

  startPage();
  addHeader();

  questions.forEach((question, questionIndex) => {
    const questionLines = wrapText(question.question, 74).length;
    const answerLines = question.answers.reduce(
      (total, answer) => total + wrapText(answer, 82).length,
      0
    );
    ensureSpace(52 + questionLines * 15 + answerLines * 14);

    addText(question.topic.toUpperCase(), margin, y, 9, theme.accent, "F2");
    y -= 16;
    addWrappedText(`${questionIndex + 1}. ${question.question}`, margin, 12, theme.text, 74, 15, "F2");
    y -= 6;

    question.answers.forEach((answer, answerIndex) => {
      const isCorrect = answerIndex === question.correct;
      const answerText = `${answerIndex + 1}. ${answer}${isCorrect ? "  - correct answer" : ""}`;
      const lines = wrapText(answerText, 82);
      const boxHeight = lines.length * 14 + 8;
      ensureSpace(boxHeight + 8);

      if (isCorrect) {
        addRectangle(margin - 6, y - boxHeight + 5, pageWidth - margin * 2 + 12, boxHeight, theme.panel);
      }

      lines.forEach((line) => {
        addText(line, margin + 10, y, 10.5, isCorrect ? theme.correct : theme.text, isCorrect ? "F2" : "F1");
        y -= 14;
      });
      y -= 4;
    });

    y -= 10;
  });

  pages.forEach((pageCommands, index) => {
    addTextToPage(pageCommands, `Page ${index + 1}`, pageWidth - margin - 42, 30, 9, theme.muted);
  });

  return new Blob([buildPdfDocument(pages, pageWidth, pageHeight)], {
    type: "application/pdf"
  });

  function addTextToPage(pageCommands, value, x, baseline, size, fill) {
    pageCommands.push(
      `BT /F1 ${size} Tf ${color(fill)} rg ${x} ${baseline} Td (${escapePdfText(value)}) Tj ET`
    );
  }
}

function buildPdfDocument(pages, pageWidth, pageHeight) {
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>"
  ];
  const pageObjectNumbers = [];
  const contentObjectNumbers = [];

  pages.forEach((pageCommands) => {
    const pageObjectNumber = objects.length + 1;
    const contentObjectNumber = pageObjectNumber + 1;
    pageObjectNumbers.push(pageObjectNumber);
    contentObjectNumbers.push(contentObjectNumber);
    objects.push(
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${pageWidth} ${pageHeight}] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${contentObjectNumber} 0 R >>`
    );
    const stream = pageCommands.join("\n");
    objects.push(`<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`);
  });

  objects[1] = `<< /Type /Pages /Kids [${pageObjectNumbers
    .map((objectNumber) => `${objectNumber} 0 R`)
    .join(" ")}] /Count ${pages.length} >>`;

  let pdf = "%PDF-1.4\n";
  const offsets = [0];

  objects.forEach((object, index) => {
    offsets.push(pdf.length);
    pdf += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });

  const xrefOffset = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.slice(1).forEach((offset) => {
    pdf += `${String(offset).padStart(10, "0")} 00000 n \n`;
  });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
  return pdf;
}

function exportPdf() {
  const pdf = createQuizPdf(document.body.classList.contains("light-mode") ? "light" : "dark");
  const url = URL.createObjectURL(pdf);
  const link = document.createElement("a");
  link.href = url;
  link.download = `history-ancient-world-glocal-${getActivePage().title
    .toLowerCase()
    .replace(/\s+/g, "-")}-mcq.pdf`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}

function handleKeyboardShortcut(event) {
  if (["1", "2", "3", "4"].includes(event.key)) {
    const answerButton = document.querySelector(
      `.answer-button[data-shortcut="${event.key}"]:not(:disabled)`
    );

    if (answerButton) {
      event.preventDefault();
      selectAnswer(answerButton);
    }

    return;
  }

  if (event.key === "Enter" && !nextButton.disabled) {
    event.preventDefault();
    moveNext();
  }
}

